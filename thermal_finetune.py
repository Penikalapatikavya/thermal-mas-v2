best = YOLO(f"{D}/runs/finetune_sim_flir/weights/best.pt")
base = YOLO(f"{D}/best_kaggle.pt")

def evaluate(model, data, split, tag):
    r = model.val(data=data, split=split, imgsz=640, batch=32, device=0, plots=False,
                  verbose=False, project="/content/eval", name=tag, exist_ok=True)
    out = {"all": (float(r.box.map50), float(r.box.map))}
    for i, cls in enumerate(r.box.ap_class_index):
        out[r.names[int(cls)]] = (float(r.box.ap50[i]), float(r.box.ap[i]))
    return out

results = {
    ("Simulation test", "before"): evaluate(base, "/content/data/combined.yaml", "test", "sim_before"),
    ("Simulation test", "after"):  evaluate(best, "/content/data/combined.yaml", "test", "sim_after"),
    ("FLIR val (real)", "before"): evaluate(base, "/content/data/flir.yaml", "val", "flir_before"),
    ("FLIR val (real)", "after"):  evaluate(best, "/content/data/flir.yaml", "val", "flir_after"),
}

